import { describe, expect, it } from '@jest/globals';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  TransitionRefusedError,
  adminApprovalValid,
  checkRemediation,
  dueAfterDenial,
  dueAfterWaiver,
  nextState,
  parseExportLines,
  parseJson,
  policyCanonical,
  policySectionIssues,
  remediationCanonical,
  remediationDueAt,
  remediationPlan,
  reviewApprovalProblem,
  reviewHolderProblem,
  stepsProblem,
  verifyEvidenceEvents,
  verifyRemediationRecord,
  verifyReviewRecord,
} from '../src/index.js';
import type {
  AdminApproval, BoundaryPolicy, ExecutorKeyInfo, PolicyGateEvaluation, RemediationDefaults, RemediationKey,
  RemediationRecord, ReviewRecord,
} from '../src/index.js';

/**
 * The `remediation` conformance suite (Genesis Mesh 1.4.0), generated by the
 * Python reference (genesismesh/conformance/generate_vectors.py) and copied
 * unchanged: remediation guidance, due times, the state table, the two new
 * records, reviews with second-holder approval, and export verification.
 * Every vector runs.
 */
interface Vector {
  id: string;
  kind: string;
  description: string;
  rule?: string;
  model?: string;
  input?: Record<string, unknown>;
  record?: Record<string, unknown>;
  key?: RemediationKey;
  plan?: { mode: string; steps: string };
  approval?: AdminApproval;
  audiences?: string[];
  public_key?: string;
  expected: Record<string, unknown>;
}

const raw = readFileSync(fileURLToPath(new URL('./fixtures/conformance/remediation.json', import.meta.url)), 'utf-8');
const suite = parseJson(raw) as { suite: string; version: string; vectors: Vector[] };

const sha256 = (text: string) => createHash('sha256').update(text, 'utf-8').digest('hex');

function outcome(v: Vector): Record<string, unknown> {
  switch (v.kind) {
    case 'policy_canonical': {
      const canonical = policyCanonical(v.record as unknown as BoundaryPolicy);
      return { canonical, digest: sha256(canonical) };
    }
    case 'policy_validation':
      return { codes: [...new Set(policySectionIssues(v.record as unknown as BoundaryPolicy).map(i => i.code))].sort() };
    case 'remediation_plan': {
      const i = v.input!;
      const plan = remediationPlan({
        verdict: i['verdict'] as string, policies: i['policies'] as BoundaryPolicy[],
        evaluations: i['gate_evaluations'] as PolicyGateEvaluation[], action: i['action'] as string,
        version_id: i['version_id'] as string | null, rotatable: i['rotatable'] as boolean,
        defaults: i['defaults'] as RemediationDefaults,
      });
      return { ...plan, remediation_due_at: remediationDueAt(i['judged_at'] as string, plan.grace_seconds) };
    }
    case 'due_time': {
      const i = v.input!;
      const due = v.rule === 'review_denial'
        ? dueAfterDenial(i['current_due'] as string | null, i['decided_at'] as string, i['grace_seconds'] as number)
        : dueAfterWaiver(i['waived_until'] as string, i['grace_seconds'] as number);
      return { remediation_due_at: due };
    }
    case 'transition':
      try {
        return { state: nextState(v.input!['state'] as string, v.input!['event'] as string) };
      } catch (err) {
        if (!(err instanceof TransitionRefusedError)) throw err;
        return { refused: err.code };
      }
    case 'canonical_form': {
      const canonical = remediationCanonical(v.record as unknown as RemediationRecord);
      return { canonical, digest: sha256(canonical) };
    }
    case 'verify_record':
      return {
        valid: v.model === 'RemediationRecord'
          ? verifyRemediationRecord(v.record as unknown as RemediationRecord, [v.public_key!])
          : verifyReviewRecord(v.record as unknown as ReviewRecord, [v.public_key!]),
      };
    case 'remediation_check':
      return { code: checkRemediation(v.record as unknown as RemediationRecord, v.key).code };
    case 'steps_problem':
      return { consistent: stepsProblem(v.plan!.mode, v.plan!.steps, v.record as unknown as RemediationRecord) === null };
    case 'admin_approval':
      return { valid: adminApprovalValid(v.approval!) };
    case 'review_approval':
      return { valid: reviewApprovalProblem(v.record as unknown as ReviewRecord, v.audiences!) === null };
    case 'review_holders':
      return { code: reviewHolderProblem(v.input as never)?.code ?? null };
    case 'verify_export': {
      const i = v.input!;
      const result = verifyEvidenceEvents(parseExportLines(i['lines'] as string), {
        naPublicKeys: i['na_public_keys'] as string[],
        executorKeys: i['executor_keys'] as ExecutorKeyInfo[],
        contiguous: i['contiguous'] as boolean,
      });
      const failures = [...new Map(result.failures.map(f => [`${f.store_sequence}\u0000${f.reason}`, f])).values()]
        .map(f => ({ store_sequence: f.store_sequence, reason: f.reason }))
        .sort((a, b) => (a.store_sequence ?? 0) - (b.store_sequence ?? 0) || (a.reason < b.reason ? -1 : 1));
      const counts = Object.fromEntries((['observations', 'break_glass', 'judgements', 'quarantined', 'remediations',
        'reviews'] as const).filter(k => result[k] !== undefined).map(k => [k, result[k]]));
      return { verified: result.verified, failures, counts };
    }
    default:
      throw new Error(`unknown vector kind ${v.kind}`);
  }
}

describe('remediation conformance vectors (v1.4.0)', () => {
  it('is the remediation suite, all 195 vectors', () => {
    expect(suite.suite).toBe('remediation');
    expect(suite.version).toBe('1.4.0');
    expect(suite.vectors).toHaveLength(195);
  });

  for (const v of suite.vectors) {
    it(`${v.id}: ${v.description}`, () => {
      expect(outcome(v)).toEqual(v.expected);
    });
  }
});
